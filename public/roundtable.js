// Пост в X — всегда по-английски, ≤ 280 знаков вместе со ссылкой (X считает её за 23)
export function shareText(d) {
  const cut = (r) => { r = String(r || "").replace(/[.!?]$/, ""); if (r.length <= 62) return r; const k = r.slice(0, 61); return k.slice(0, Math.max(35, k.lastIndexOf(" "))).replace(/[,;:\s]+$/, "") + "…"; };
  const hs = (d && Array.isArray(d.topics) ? d.topics : []).slice(0, 2).map((t) => "• " + cut(t.headline));
  return T.en.shareTxt + (hs.length ? ":\n\n" + hs.join("\n") + "\n\n" + T.en.watch : ". " + T.en.watch);
}
// Реплики очереди → что показать; «нет ответа» гостя показываем коротко и только в первой теме
export function playable(lines, t) {
  const out = [], told = new Set();
  for (const x of lines || []) {
    if (x.part !== "absent") { out.push(x); continue; }
    const key = x.who + ":" + x.status; if (told.has(key) && x.status === "off") continue; told.add(key);
    const tpl = x.status === "off" ? t.off : x.status === "withheld" ? t.withheld : t.err;
    out.push({ ...x, text: tpl.replace("{n}", NAMES[x.who] || x.who), label: true, audio: null });
  }
  return out;
}

